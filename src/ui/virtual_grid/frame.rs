use super::*;

// Holds the shared inputs used to paint one virtual grid frame.
pub(super) struct GridViewportFrame<'a> {
    pub(super) grid: GridTable<'a>,
    pub(super) display: GridDisplay,
    pub(super) input: GridInput<'a>,
    pub(super) state: GridState<'a>,
    pub(super) document_id: DocumentId,
    pub(super) table_id: u64,
    pub(super) row_layout: &'a GridRowLayout,
    pub(super) row_header_width: f32,
    pub(super) selection: CellRange,
    pub(super) active_cell: CellAddress,
    pub(super) header_row: Option<usize>,
    pub(super) frozen_row_count: usize,
    pub(super) frozen_column_count: usize,
    pub(super) row_count: usize,
    pub(super) column_count: usize,
    pub(super) effective_scroll_x: f32,
    pub(super) effective_scroll_y: f32,
    pub(super) viewport_rect: Rect,
    pub(super) viewport_origin: Pos2,
    pub(super) body_min: Pos2,
    pub(super) frozen_x: f32,
    pub(super) frozen_y: f32,
    pub(super) frozen_width: f32,
    pub(super) frozen_height: f32,
    pub(super) visible_rows: Vec<usize>,
    pub(super) visible_columns: Vec<usize>,
    pub(super) render_cells: BTreeSet<(usize, usize)>,
    pub(super) pane_zones: [GridPaneZone; 4],
    pub(super) selected_ranges: Vec<(CellAddress, CellAddress)>,
    /// Normalized target of an active fill-handle drag, outlined instead of the selection.
    pub(super) fill_preview: Option<(CellAddress, CellAddress)>,
    pub(super) visuals: egui::Visuals,
    pub(super) palette: GridThemePalette,
}
